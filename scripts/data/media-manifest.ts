export type Rights = { status: "cleared" | "unconfirmed"; note: string };

/** Provisional rights status from the filename. The owner confirms in Admin → Media. */
export function classifyRights(path: string): Rights {
  const name = path.split("/").pop()!;
  if (/-utc(-\d+)?\.jpe?g$/i.test(name))
    return {
      status: "unconfirmed",
      note: "Stock photo from the WordPress theme demo (Envato Elements filename pattern). Licence for this site not confirmed.",
    };
  if (name === "Steak-Sizzling.mp4")
    return { status: "unconfirmed", note: "Generic stock-style clip of unknown origin. Confirm it was filmed for Hot Rock or is licensed." };
  if (/^[A-Z0-9]{24}\.(webp|jpe?g)$/.test(name))
    return {
      status: "cleared",
      note: "Hot Rock food photography (Hot Rock watermark or branded cleaver visible). The generated filename suggests an editing or AI tool export; confirm origin.",
    };
  return { status: "cleared", note: "Owner-supplied photo or graphic from the existing website." };
}
